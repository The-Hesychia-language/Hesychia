/// Keeps the arguments for `os.args()`, and makes the module constants.
const ARGS: &str = "hsy_argc = argc;\n    hsy_argv = argv;\n    hsy_init_globals();\n    ";

impl Emitter<'_> {
    fn emit_program(&mut self, program: &Program) -> String {
        // Operators the generated code calls by itself; `c[k]`, `x in c` and the like are
        // calls in the program already.
        const IMPLICIT: [&str; 9] = ["add", "sub", "mul", "div", "mod", "equal", "compare", "show", "drop"];
        // Each such method, and the C name of its struct: it is written only once the rest
        // of the code uses that struct.
        let waiting: HashMap<String, String> = self
            .types
            .table
            .structs
            .iter()
            .enumerate()
            .flat_map(|(id, s)| {
                // As `TypeRegistry` names them: `Pair[i32]` by its template and id.
                let owner = match s.name.split_once('[') {
                    Some((base, _)) => format!("hsy_m{}_{base}__{id}", s.module),
                    None => format!("hsy_m{}_{}", s.module, s.name),
                };
                s.operators
                    .iter()
                    .filter(|(m, _)| IMPLICIT.contains(&m.as_str()))
                    .map(move |(_, c)| (c.clone(), owner.clone()))
            })
            .collect();
        let mut roots: Vec<String> = waiting.keys().cloned().collect();
        roots.extend(self.types.panic_handler.clone());
        let used = reach::reachable(program, roots);
        let (mut deferred, mut bodies): (Vec<_>, Vec<_>) =
            functions(program, &used).into_iter().partition(|(c_name, _)| waiting.contains_key(c_name));
        for (c_name, f) in &bodies {
            self.emit_fn(c_name, f);
        }
        let globals = self.emit_globals(program, &used);
        let entry = self.c_main(program);
        loop {
            let (ready, rest): (Vec<_>, Vec<_>) =
                deferred.into_iter().partition(|(c_name, _)| self.types.is_defined(&waiting[c_name]));
            deferred = rest;
            if ready.is_empty() {
                break;
            }
            for (c_name, f) in &ready {
                self.emit_fn(c_name, f);
            }
            bodies.extend(ready);
        }
        let declarations = self.declarations(program, &bodies, &used);
        let panic = self.panic_definition();
        format!(
            "{PRELUDE}{}{}{declarations}{globals}\n{}{}{}{entry}{panic}",
            self.types.render(),
            self.helpers.render(),
            self.types.render_functions(),
            self.lambdas,
            self.out
        )
    }

    /// The used module constants, and the function that makes them before `main`, in the
    /// order modules were loaded backwards: a module's imports come first.
    fn emit_globals(&mut self, program: &Program, used: &HashSet<String>) -> String {
        let mut statics = String::new();
        self.line("static void hsy_init_globals(void) {");
        self.indent += 1;
        for (index, module) in program.modules.iter().enumerate().rev() {
            for item in &module.items {
                let Item::Global(g) = item else { continue };
                let c_name = crate::ast::global_c_name(index, &expr::c_ident(&g.name));
                if !used.contains(&crate::ast::global_c_name(index, &g.name)) {
                    continue;
                }
                statics += &format!("static {} {c_name};\n", self.types.c_type(g.value.ty()));
                let value = self.emit_expr(&g.value);
                self.line(&format!("{c_name} = {value};"));
            }
        }
        self.indent -= 1;
        self.line("}");
        statics
    }

    /// Prototypes for the used functions, and one declaration per distinct used extern.
    fn declarations(
        &mut self,
        program: &Program,
        bodies: &[(String, &FnDecl)],
        used: &HashSet<String>,
    ) -> String {
        let mut out = String::new();
        let mut externs = HashSet::new();
        for item in program.modules.iter().flat_map(|m| &m.items) {
            if let Item::Extern(e) = item
                && used.contains(&format!("hsy_extern_{}", e.name))
                && externs.insert(&e.name)
            {
                out += &self.extern_declaration(e);
            }
        }
        for (c_name, f) in bodies {
            out += &format!("{};\n", self.fn_header(c_name, f));
        }
        out
    }

    fn emit_fn(&mut self, c_name: &str, f: &FnDecl) {
        let header = self.fn_header(c_name, f);
        self.line(&format!("{header} {{"));
        let sig = &self.signatures[c_name];
        let params = &sig.params;
        self.fn_ret = sig.ret.clone();
        self.fn_raises = sig.raises.clone();
        let mut names: Vec<&str> = f.params.iter().map(|p| p.name.as_str()).collect();
        if params.len() > names.len() {
            names.insert(0, "self");
        }
        let owned: Vec<(String, crate::types::Type)> =
            names.iter().zip(params.clone()).map(|(n, t)| (expr::c_ident(n), t)).collect();
        self.indent += 1;
        // A parameter the body does not read is fine in Hesychia; C would warn about it.
        let unused: String = owned.iter().map(|(name, _)| format!("(void){name}; ")).collect();
        if !unused.is_empty() {
            self.line(unused.trim_end());
        }
        self.open_scope(false);
        for (name, ty) in owned {
            self.own(name, ty);
        }
        self.indent -= 1;
        self.emit_body(&f.body);
        self.indent += 1;
        let jumped = stmt::ends_with_jump(&f.body);
        self.close_scope(jumped);
        if !jumped && !self.fn_raises.is_empty() && self.fn_ret == Type::Void {
            let ok = self.wrap_return(None);
            self.line(&format!("return {ok};"));
        }
        // The checker proved that every path returns; C cannot always see it.
        if !jumped && self.fn_ret != Type::Void {
            self.line("__builtin_unreachable();");
        }
        self.indent -= 1;
        self.line("}\n");
    }

    fn fn_header(&mut self, c_name: &str, f: &FnDecl) -> String {
        let mut names: Vec<&str> = f.params.iter().map(|p| p.name.as_str()).collect();
        let sig = &self.signatures[c_name];
        let (params, ret, raises) = (&sig.params, &sig.ret, &sig.raises);
        if params.len() > names.len() {
            names.insert(0, "self");
        }
        let ret =
            if raises.is_empty() { self.types.c_type(ret) } else { self.types.result_type(ret, raises) };
        format!("HSY_UNUSED static {ret} {c_name}({})", self.c_params(params, &names, false))
    }

    /// Declares a C function under our own name, bound to the real symbol with an asm label.
    fn extern_declaration(&mut self, e: &ExternFn) -> String {
        let c_name = format!("hsy_extern_{}", e.name);
        let sig = &self.signatures[&c_name];
        let (params, ret) = (&sig.params, &sig.ret);
        let names: Vec<&str> = e.params.iter().map(|p| p.name.as_str()).collect();
        let ret = self.types.c_type(ret);
        let params = self.c_params(params, &names, e.variadic);
        format!("{ret} {c_name}({params}) __asm__(HSY_SYMBOL(\"{}\"));\n", e.symbol)
    }

    fn c_params(&mut self, types: &[Type], names: &[&str], variadic: bool) -> String {
        let mut parts: Vec<String> = types
            .iter()
            .zip(names)
            .map(|(ty, name)| format!("{} {}", self.types.c_type(ty), expr::c_ident(name)))
            .collect();
        if variadic {
            parts.push("...".into());
        }
        if parts.is_empty() { "void".into() } else { parts.join(", ") }
    }

    fn line(&mut self, text: &str) {
        self.out += &"    ".repeat(self.indent);
        self.out += text;
        self.out.push('\n');
    }

    fn temp(&mut self, purpose: &str) -> String {
        self.temps += 1;
        // Shaped unlike type names (`hsy_tuple_3`), so the two never collide.
        format!("hsy_v{}_{purpose}", self.temps)
    }
}

/// Every used function and method with a body, by C name, in source order.
fn functions<'p>(program: &'p Program, used: &HashSet<String>) -> Vec<(String, &'p FnDecl)> {
    let mut out = Vec::new();
    for (index, module) in program.modules.iter().enumerate() {
        for item in &module.items {
            match item {
                Item::Fn(f) if f.generics.is_empty() => out.push((fn_c_name(index, &f.name), f)),
                Item::Struct(s) if s.generics.is_empty() => {
                    let methods = s.methods.iter().filter(|m| m.generics.is_empty());
                    out.extend(methods.map(|m| (method_c_name(index, &s.name, &m.name), m)));
                }
                _ => {}
            }
        }
    }
    out.retain(|(name, _)| used.contains(name));
    out
}

impl Emitter<'_> {
    /// What a fault does: call the `@panic_handler` with a message, if there is one, then stop.
    fn panic_definition(&self) -> String {
        let call = match &self.types.panic_handler {
            Some(handler) => {
                let text = "the program stopped on a fault";
                format!(
                    "hsy_str message = {{(char*)\"{text}\", {}, 0}};\n    {handler}(&message);\n    fflush(stdout);\n    ",
                    text.len()
                )
            }
            None => String::new(),
        };
        format!("\nstatic void hsy_panic(void) {{\n    {call}__builtin_trap();\n}}\n")
    }

    /// The C entry point calls the Hesychia `main` of the first module. An error escaping
    /// a `managed` `main` stops the program with its type.
    fn c_main(&mut self, program: &Program) -> String {
        let returns_value = program.modules[0]
            .items
            .iter()
            .any(|item| matches!(item, Item::Fn(f) if f.name == "main" && f.ret.is_some()));
        let main = fn_c_name(0, "main");
        let sig = &self.signatures[&main];
        // Cycles of `shared` values still alive are collected before the program ends.
        let exit = if self.types.uses_shared { "hsy_shared_exit();\n    " } else { "" };
        if sig.raises.is_empty() {
            let call = if returns_value {
                format!("int r = {main}();\n    {exit}return r;")
            } else {
                format!("{main}();\n    {exit}return 0;")
            };
            return format!("int main(int argc, char** argv) {{\n    {ARGS}{call}\n}}\n");
        }
        let (ret, raises) = (sig.ret.clone(), sig.raises.clone());
        let result = self.types.result_type(&ret, &raises);
        let names: String = raises.iter().map(|e| format!("\"{e}\", ")).collect();
        let value = if returns_value { "r.value" } else { "0" };
        format!(
            "int main(int argc, char** argv) {{\n    {ARGS}static const char* errors[] = {{ {names}}};\n    {result} r = {main}();\n    \
             if (r.err) {{\n        fprintf(stderr, \"error: `%s` was raised and not caught\\n\", errors[r.err - 1]);\n        \
             return 1;\n    }}\n    {exit}return {value};\n}}\n"
        )
    }
}
