pub struct Options {
    /// Emits `#line` directives that map C back to the `.hsy` sources.
    pub debug: bool,
    /// Source paths, indexed by file id.
    pub file_names: Vec<String>,
    /// The `@test` function the program runs: a failure says which of its lines it was on.
    pub test: Option<String>,
}

pub fn generate(program: &Program, checked: &Checked, options: &Options) -> String {
    let mut emitter = Emitter {
        out: String::new(),
        indent: 0,
        temps: 0,
        helpers: Helpers::default(),
        types: TypeRegistry::new(&checked.types, checked.panic_handler.clone()),
        scopes: Vec::new(),
        fn_ret: Type::Void,
        fn_raises: Vec::new(),
        tries: Vec::new(),
        borrowed_match: Vec::new(),
        in_test: false,
        lambdas: String::new(),
        signatures: &checked.signatures,
        options,
    };
    emitter.emit_program(program)
}

struct Emitter<'a> {
    out: String,
    indent: usize,
    /// Counter for compiler-made temporaries.
    temps: usize,
    helpers: Helpers,
    types: TypeRegistry<'a>,
    /// The function being emitted is the test the program runs.
    in_test: bool,
    /// Variables to release at the end of each open block, innermost last.
    scopes: Vec<owned::Scope>,
    /// For each `match` being emitted, innermost last: whether it only borrows its subject.
    borrowed_match: Vec<bool>,
    signatures: &'a HashMap<String, Signature>,
    /// The function being emitted: its return and error types.
    fn_ret: Type,
    fn_raises: Vec<Type>,
    /// The open `try` blocks, innermost last.
    tries: Vec<errors::TryFrame>,
    /// The C functions made for lambdas.
    lambdas: String,
    options: &'a Options,
}

