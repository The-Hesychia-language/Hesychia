#!/usr/bin/env python3
"""Writes stdlib/casing.hsy, the Unicode case tables of `str.upper` and `str.lower`.

The tables come from Python's own Unicode data, so they follow its version:
    python3 tools/unicode_case.py > stdlib/casing.hsy

The data is emitted as Hesychia `array` tables; the binary searches over them live in
tools/case_lookup.hsy, appended below so the module is self-contained.
"""
import unicodedata

CODES = [c for c in range(0x110000) if not 0xD800 <= c < 0xE000]


def ranges(pairs):
    """(first, last, delta, stride) runs of code points that move by the same delta."""
    out, i = [], 0
    while i < len(pairs):
        c, d = pairs[i]
        j, stride = i + 1, 1
        if j < len(pairs) and pairs[j][1] == d and pairs[j][0] - c in (1, 2):
            stride = pairs[j][0] - c
            while j < len(pairs) and pairs[j][1] == d and pairs[j][0] - pairs[j - 1][0] == stride:
                j += 1
        out.append((c, pairs[j - 1][0], d, stride))
        i = j
    return out


def spans(codes):
    out = []
    for c in codes:
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def column(name, kind, values):
    """One Hesychia table `name: array[kind, len] = [...]`, and its length constant `name_n`."""
    cells = ", ".join(str(v) for v in values)
    print(f"priv comptime {name}: array[{kind}, {len(values)}] = [{cells}]")


def length(name, n):
    print(f"priv comptime {name}_n: size = {n}")


def table(name, case):
    single = [(c, ord(case(chr(c))) - c) for c in CODES if len(case(chr(c))) == 1 and case(chr(c)) != chr(c)]
    rows = ranges(single)
    column(f"{name}_first", "u32", [r[0] for r in rows])
    column(f"{name}_last", "u32", [r[1] for r in rows])
    column(f"{name}_delta", "i32", [r[2] for r in rows])
    column(f"{name}_stride", "u32", [r[3] for r in rows])
    length(name, len(rows))
    print()
    many = [(c, case(chr(c))) for c in CODES if len(case(chr(c))) > 1]
    cell = lambda row, k: ord(row[1][k]) if k < len(row[1]) else 0
    column(f"{name}_many_cp", "u32", [m[0] for m in many])
    column(f"{name}_many_first", "u32", [cell(m, 0) for m in many])
    column(f"{name}_many_second", "u32", [cell(m, 1) for m in many])
    column(f"{name}_many_third", "u32", [cell(m, 2) for m in many])
    length(f"{name}_many", len(many))
    print()


def cased(c):
    ch = chr(c)
    return unicodedata.category(ch) in ("Lu", "Ll", "Lt") or ch.upper() != ch or ch.lower() != ch


IGNORABLE = set("'.:^`·‘’․‧︓﹒﹕＇．：")


def ignorable(c):
    ch = chr(c)
    return unicodedata.category(ch) in ("Mn", "Me", "Cf", "Lm", "Sk") or ch in IGNORABLE


def set_table(name, test):
    rows = spans([c for c in CODES if test(c)])
    column(f"{name}_first", "u32", [r[0] for r in rows])
    column(f"{name}_last", "u32", [r[1] for r in rows])
    length(name, len(rows))
    print()


print(f"# Generated by tools/unicode_case.py from Unicode {unicodedata.unidata_version}; do not edit.")
print("# The Unicode case tables of `str.upper` and `str.lower`: ranges that shift by a fixed")
print("# delta, the few code points that expand to several, and the sets `str` consults around a")
print("# final sigma. Every table is sorted by code point for the binary searches below.")
print()
table("upper", str.upper)
table("lower", str.lower)
set_table("cased", cased)
set_table("ignorable", ignorable)
with open(__file__.replace("unicode_case.py", "case_lookup.hsy")) as f:
    print(f.read(), end="")
