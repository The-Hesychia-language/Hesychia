#!/usr/bin/env python3
"""Writes src/codegen/case.c, the Unicode case tables of `str.upper` and `str.lower`.

The tables come from Python's own Unicode data, so they follow its version:
    python3 tools/unicode_case.py > src/codegen/case.c
"""
import sys
import unicodedata

CODES = [c for c in range(0x110000) if not 0xD800 <= c < 0xE000]


def ranges(pairs):
    """(first, last, delta, stride) runs of code points that move by the same delta."""
    out, i = [], 0
    while i < len(pairs):
        c, d = pairs[i]
        j, stride = i + 1, 1
        if j < len(pairs) and pairs[j][1] == d and pairs[j][0] - c in (1, 2):
            stride = pairs[j][0] - c
            while j < len(pairs) and pairs[j][1] == d and pairs[j][0] - pairs[j - 1][0] == stride:
                j += 1
        out.append((c, pairs[j - 1][0], d, stride))
        i = j
    return out


def spans(codes):
    out = []
    for c in codes:
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def table(name, case):
    single = [(c, ord(case(chr(c))) - c) for c in CODES if len(case(chr(c))) == 1 and case(chr(c)) != chr(c)]
    rows = ranges(single)
    print(f"static const hsy_case_range {name}[{len(rows)}] = {{")
    for first, last, delta, stride in rows:
        print(f"    {{0x{first:X}, 0x{last:X}, {delta}, {stride}}},")
    print("};\n")
    many = [(c, case(chr(c))) for c in CODES if len(case(chr(c))) > 1]
    print(f"static const uint32_t {name}_many[{len(many)}][4] = {{")
    for c, text in many:
        cells = ", ".join(f"0x{ord(x):X}" for x in text.ljust(3, "\0"))
        print(f"    {{0x{c:X}, {cells}}},")
    print("};\n")


def cased(c):
    ch = chr(c)
    return unicodedata.category(ch) in ("Lu", "Ll", "Lt") or ch.upper() != ch or ch.lower() != ch


IGNORABLE = set("'.:^`·‘’․‧︓﹒﹕＇．：")


def ignorable(c):
    ch = chr(c)
    return unicodedata.category(ch) in ("Mn", "Me", "Cf", "Lm", "Sk") or ch in IGNORABLE


def set_table(name, test):
    rows = spans([c for c in CODES if test(c)])
    print(f"static const uint32_t {name}[{len(rows)}][2] = {{")
    for first, last in rows:
        print(f"    {{0x{first:X}, 0x{last:X}}},")
    print("};\n")


print(f"/* Generated by tools/unicode_case.py from Unicode {unicodedata.unidata_version}; do not edit. */")
print("typedef struct { uint32_t first, last; int32_t delta; uint32_t stride; } hsy_case_range;\n")
table("hsy_case_upper", str.upper)
table("hsy_case_lower", str.lower)
set_table("hsy_case_cased_set", cased)
set_table("hsy_case_ignorable_set", ignorable)
sys.stdout.write(open(__file__.replace("unicode_case.py", "case_lookup.c")).read())
